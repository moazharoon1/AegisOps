"""Secret redaction applied before data enters prompts, evidence, artifacts, logs, traces or reports.

Two mechanisms:
1. Value patterns (credentials embedded in any string, including the synthetic canary).
2. Sensitive keys (string values under keys such as `password`, `api_key`, `authorization`).

`redact()` returns the redacted value and the number of redactions, which tools report so the
dashboard can show that redaction happened without revealing what was removed.
"""

from __future__ import annotations

import re
from typing import Any

REDACTED = "[REDACTED]"

# The synthetic payment credentials generated by bootstrap always contain this marker, so tests can
# prove the canary never reaches prompts, logs, traces, reports or stored evidence.
CANARY_MARKER = "sk_canary_"

VALUE_PATTERNS: list[tuple[str, re.Pattern[str]]] = [
    ("canary", re.compile(r"sk_canary_[A-Za-z0-9_]+")),
    ("stripe_like_key", re.compile(r"\b[sr]k_(?:live|test)_[A-Za-z0-9]{8,}\b")),
    ("openai_key", re.compile(r"\bsk-(?:proj-|svcacct-)?[A-Za-z0-9_-]{20,}\b")),
    ("jwt", re.compile(r"\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\b")),
    ("bearer", re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/=-]{8,}")),
    ("aws_access_key", re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b")),
    ("url_credentials", re.compile(r"(?i)\b([a-z][a-z0-9+.-]*://)[^/\s:@]+:[^/\s@]+@")),
    ("private_key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]+?-----END [A-Z ]*PRIVATE KEY-----")),
    ("kv_secret", re.compile(r"(?i)\b(password|passwd|pwd|secret|api[_-]?key|token)\s*[=:]\s*[^\s,;&\"']{4,}")),
    ("localstack_token", re.compile(r"\bls-[A-Za-z0-9]{4,}-[A-Za-z0-9-]{8,}\b")),
]

SENSITIVE_KEY = re.compile(
    r"(?i)(password|passwd|secret_?value|secretstring|secret_string|api[_-]?key|apikey|authorization|"
    r"credential|private[_-]?key|approval_token|access[_-]?token|refresh[_-]?token|session[_-]?token|"
    r"auth[_-]?token|^token$|client[_-]?secret)"
)
# Keys that look sensitive but only hold identifiers or counts.
SAFE_KEYS = frozenset(
    {
        "secret_id",
        "secret_name",
        "secret",  # secret *name* in metrics labels
        "version_id",
        "current_version_id",
        "previous_version_id",
        "known_good_version_id",
        "token_id",
        "input_tokens",
        "output_tokens",
        "cached_input_tokens",
        "max_tokens",
    }
)


def redact_text(text: str) -> tuple[str, int]:
    count = 0
    for name, pattern in VALUE_PATTERNS:
        if name == "url_credentials":
            text, n = pattern.subn(lambda m: f"{m.group(1)}{REDACTED}@", text)
        elif name == "kv_secret":
            text, n = pattern.subn(lambda m: f"{m.group(1)}={REDACTED}", text)
        else:
            text, n = pattern.subn(REDACTED, text)
        count += n
    return text, count


def _is_sensitive_key(key: str) -> bool:
    return key not in SAFE_KEYS and bool(SENSITIVE_KEY.search(key))


def redact(value: Any) -> tuple[Any, int]:
    """Recursively redact strings, dicts, lists and tuples. Non-string scalars are returned as-is."""
    if isinstance(value, str):
        return redact_text(value)
    if isinstance(value, dict):
        total = 0
        out: dict[Any, Any] = {}
        for key, item in value.items():
            if isinstance(key, str) and _is_sensitive_key(key) and isinstance(item, str) and item:
                out[key] = REDACTED
                total += 1
                continue
            out[key], n = redact(item)
            total += n
        return out, total
    if isinstance(value, list | tuple):
        total = 0
        items = []
        for item in value:
            red, n = redact(item)
            items.append(red)
            total += n
        return (items if isinstance(value, list) else tuple(items)), total
    return value, 0


def contains_secret(text: str) -> bool:
    """True if `text` still contains anything a value pattern would redact (used by tests/guards)."""
    return any(pattern.search(text) for _, pattern in VALUE_PATTERNS)


def contains_canary(text: str) -> bool:
    return CANARY_MARKER in text
